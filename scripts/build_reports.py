"""Build _report/ (gitignored everywhere): one page per function, and the hub _report/index.html (never hand-edited). Run: uv run python scripts/build_reports.py"""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "_report"
STYLE = ("<style>:root{--bg:#fff;--fg:#1a1a1a;--mute:#666;--line:#ddd;--ok:#1a7f37;--bad:#cf222e}"
         "@media (prefers-color-scheme:dark){:root{--bg:#111;--fg:#eee;--mute:#999;--line:#333;--ok:#3fb950;--bad:#f85149}}"
         "body{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;max-width:1000px;margin:0 auto;padding:16px}"
         "table{border-collapse:collapse;width:100%}td,th{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}"
         ".ok{color:var(--ok)}.bad{color:var(--bad)}.mute{color:var(--mute)}</style>")


def page(path, title, purpose, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
                    f'<meta name="report:purpose" content="{html.escape(purpose)}"><title>{html.escape(title)}</title>{STYLE}</head>'
                    f"<body><h1>{html.escape(title)}</h1><p>{html.escape(purpose)}</p>{body}</body></html>\n")


def regraded(r):
    """A run graded again after its grader changed: both scores stay, the new one beside the old."""
    g = r.get("regraded")
    return f" <span class='mute' title='{html.escape(g['why'])}'>→ regraded {g['passed']}/{g['total']}</span>" if g else ""


def viz_link(r):
    """The run's store as the panel draws it (scripts/viz_evals.py), when its pages were built."""
    name = Path(r.get("grade") or r.get("check", "")).parent.name   # "check": rows before #11
    return f"<a href='../viz/evals/{html.escape(name)}/index.html'>open</a>" if name and (REPORT / "viz" / "evals" / name / "index.html").exists() else "—"


def haiku_evals():
    rows = [json.loads(x) for x in (ROOT / "evals/haiku/results.jsonl").read_text().splitlines() if x.strip()]
    body = ["<p class='mute'>Each eval: <code>evals/haiku/&lt;tool&gt;_basics.py</code>. Setup makes a fresh Postgres database (the throwaway cluster) and a synthetic file; a haiku "
            "agent (Claude Haiku as a subagent, or a local model such as Qwen through opencode: evals/run_agent_eval.py) gets only the eval's TASK text (no skill pasted, no hints); the checker inspects the store. Criteria are mechanical "
            "(nodes, tables, columns, actors); the agent's own report is not scored.</p><table><tr><th>eval</th><th>run</th><th>date</th>"
            "<th>model</th><th>result</th><th>viz</th><th>tool calls</th><th>tokens</th><th>seconds</th><th>commit</th><th>notes</th></tr>"]
    for r in rows:
        cls = "ok" if r["passed"] == r["total"] else "bad"
        body.append(f"<tr><td>{r['eval']}{' · ' + r['mode'] if r.get('mode') else ''}</td><td>{r['run']}</td><td>{r['date']}</td><td>{html.escape(r.get('model', ''))}</td><td class='{cls}'>{r['passed']}/{r['total']}{regraded(r)}</td><td>{viz_link(r)}</td>"
                    f"<td>{r['tool_calls']}</td><td>{r['tokens'] if r.get('tokens') is not None else '—'}</td><td>{r['seconds'] if r.get('seconds') is not None else '—'}</td><td>{html.escape(r['commit'])}</td>"
                    f"<td>{html.escape(r['notes'])}</td></tr>")
    body.append("</table>")
    page(REPORT / "haiku" / "haiku_evals.html", "Agent tool evals",
         "Can a small agent (Haiku, Qwen 27B, …) do each bitt tool's basics from its skill alone? One row per run.", "".join(body))


def hub():
    items = []
    for p in sorted(REPORT.rglob("*.html")):
        if p.name == "index.html":
            continue
        txt = p.read_text()
        purpose = txt.split('name="report:purpose" content="', 1)[1].split('"', 1)[0] if "report:purpose" in txt else ""
        items.append(f"<li><a href='{p.relative_to(REPORT)}'>{p.relative_to(REPORT)}</a>: {purpose}</li>")
    page(REPORT / "index.html", "bitt reports", "Every report page in this repo, with its purpose (generated by scripts/build_reports.py).",
         "<ul>" + "".join(items) + "</ul>")


if __name__ == "__main__":
    haiku_evals()
    hub()
    print(f"built {REPORT}/index.html")

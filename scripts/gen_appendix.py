"""Generate the card appendix of spec/kernel-contract.md from the cards (spec/cards) (so the spec never drifts from them).
Run: uv run python scripts/gen_appendix.py > spec/kernel-contract-cards.md"""
from bitt import cards as lint

cards, roots, _ = lint.load()
eff = {c: lint.effective(c, cards) for c in cards}
BASE_IN = {"actor"}


def fmt(fields, skip=()):
    out = []
    for k, f in fields.items():
        if k in skip:
            continue
        if isinstance(f, dict) and "ref" in f:
            r = "/".join(lint.as_list(f["ref"]))
            st = f"({','.join(f['state'])})" if f.get("state") else ""
            out.append(f"{k}→{r}{st}{'[]' if f.get('many') else ''}")
        elif isinstance(f, dict) and "ref_out" in f:
            out.append(f"{k} ({'/'.join(lint.as_list(f['ref_out']))})")
        else:
            out.append(k)
    return ", ".join(out) or "—"


print("# Kernel contract: card appendix (generated by scripts/gen_appendix.py; do not hand-edit)\n")
print(f"Roots (no upstream): {', '.join(sorted(roots))}. Every maneuver also carries `actor` and runs the three universal rules "
      "(`record.resolve` on every ref, `control.task_boundary` on every ref input, `control.goal_drift` on every input), not repeated below. "
      f"`any` = base.yaml `default_open_in`. Contract version {lint.META['contract_version']}.\n")
for tool in lint.DAG[::-1] + ["base"]:
    rows = [c for c in sorted(cards) if eff[c]["tool"] == tool]
    if not rows:
        continue
    print(f"\n## {tool}\n")
    print("| card | kind | open in | MIN in | OPT in | MIN out | requires |")
    print("|---|---|---|---|---|---|---|")
    for c in rows:
        e = eff[c]
        def one(r):
            extra = [f"when {r['when']}"] if r.get("when") else []
            extra += [f"acked→{r['if_acked']}"] if r.get("if_acked") else []
            extra += [f"unknown→{r['on_unknown']}"] if r.get("on_unknown") else []
            extra += ["at job.finish"] if r.get("deferred") else []
            return f"{r['rule']} [{r.get('on_fail', 'refuse')}{'; ' + '; '.join(extra) if extra else ''}] on `{r.get('subject')}`"
        req = "<br>".join(one(r) for r in e.get("requires", [])
                          if r.get("rule") not in ("record.resolve", "control.goal_drift", "control.task_boundary"))
        print(f"| `{c}` | {e['kind']} | {', '.join(e.get('open_in', [])) or ('any' if e['kind'] == 'maneuver' else '—')} "
              f"| {fmt(lint.fields(e, 'in', 'min'), BASE_IN)} | {fmt(lint.fields(e, 'in', 'opt'))} "
              f"| {fmt(lint.fields(e, 'out', 'min'), {'stamp', 'event'})} | {req or '—'} |")
